/* ─────────── ChatGPT Work reply parser (caption options) ─────────── */

type ParsedDraftOption = {
  hook: string;
  body: string;
  cta?: string;
  format?: string;
  notes?: string;
};

/**
 * parseDraftOptionsReply.
 *
 * ChatGPT Work returns Markdown with 3 numbered options. Each option includes a
 * Hook line, Body paragraphs, a CTA line, and a Format suggestion. The
 * exact layout the prompt asks for is:
 *
 *   1. Option 1
 *   - **Hook** — text...
 *   - **Body** — text...
 *   - **CTA** — text...
 *   - **Format** — text...
 *
 * ChatGPT Work's Markdown rendering varies — sometimes it uses headings, sometimes
 * bullets, sometimes bold labels. This parser tolerates the common shapes
 * and returns up to 3 ParsedDraftOption objects. Empty result -> error.
 */
function parseDraftOptionsReply(
  raw: string
): { ok: true; value: ParsedDraftOption[] } | { ok: false; error: string } {
  const reel = parseReelReply(raw);
  if (reel) return reel;
  const body = stripCodeFences(raw);
  // Split into option blocks. Look for "Option N" / "## N" / "**Option N**" /
  // "N." at the start of a line. Fall back to splitting on horizontal rules.
  const blocks = body
    .split(/^\s*(?:#{1,3}\s*)?(?:\*\*\s*)?(?:Option\s+)?\d+[.):]\s*(?:\*\*\s*)?/gim)
    .map((b) => b.trim())
    .filter((b) => b.length > 0);

  // Field-extraction regexes. The separator character class accepts colon,
  // hyphen, and U+2014 em-dash (—) because ChatGPT Work occasionally emits
  // them between label and value even when we ask for plain colons. We use
  // the Unicode escape rather than a literal so this file stays em-dash-free
  // in source. The construction is split out so the character class is
  // defined once and reused for clarity.
  const sep = "[:\\-\\u2014]";
  const options: ParsedDraftOption[] = [];
  for (const block of blocks) {
    const hook = extractField(block, new RegExp(`(?:^|\\n)\\s*[-*]?\\s*\\*?\\*?Hook\\*?\\*?\\s*${sep}\\s*(.+?)(?=\\n\\s*[-*]?\\s*\\*?\\*?(?:Body|CTA|Format)|\\n\\n|$)`, "is"));
    const bodyText = extractField(block, new RegExp(`(?:^|\\n)\\s*[-*]?\\s*\\*?\\*?Body\\*?\\*?\\s*${sep}\\s*([\\s\\S]+?)(?=\\n\\s*[-*]?\\s*\\*?\\*?(?:CTA|Format)|$)`, "is"));
    const cta = extractField(block, new RegExp(`(?:^|\\n)\\s*[-*]?\\s*\\*?\\*?CTA\\*?\\*?\\s*${sep}\\s*(.+?)(?=\\n\\s*[-*]?\\s*\\*?\\*?Format|\\n\\n|$)`, "is"));
    const format = extractField(block, new RegExp(`(?:^|\\n)\\s*[-*]?\\s*\\*?\\*?Format\\*?\\*?\\s*${sep}\\s*(.+?)(?=\\n\\n|$)`, "is"));
    if (hook || bodyText) {
      options.push({
        hook: cleanLine(hook ?? ""),
        body: cleanLine(bodyText ?? ""),
        cta: cta ? cleanLine(cta) : undefined,
        format: format ? cleanLine(format) : undefined,
      });
    }
    if (options.length === 3) break;
  }

  if (options.length === 0) {
    return {
      ok: false,
      error:
        "Nisam prepoznala opis ni Reel skriptu. Zalijepi cijeli odgovor: opis s Hook/Body/CTA/Format oznakama ili Reel s FORMAT, kadrovima i CAPTION odjeljkom.",
    };
  }
  return { ok: true, value: options };
}

function extractField(text: string, re: RegExp): string | null {
  const m = text.match(re);
  return m && m[1] ? m[1].trim() : null;
}

function cleanLine(s: string): string {
  return s
    .replace(/^\*\*|\*\*$/g, "")
    .replace(/^["'`]|["'`]$/g, "")
    .trim();
}

/**
 * Convert an ISO timestamp to the `YYYY-MM-DDTHH:MM` local-time string that
 * <input type="datetime-local"> expects. Browsers refuse anything else, and
 * passing an ISO directly leaves the input empty without explanation.
 */
function toLocalInput(iso: string): string {
  const d = new Date(iso);
  if (isNaN(d.getTime())) return "";
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

/**
 * ScheduleControl — sits on a card whose status is "draft". Customer picks
 * a date+time, then hits Schedule, and the draft moves to status=scheduled
 * with scheduled_for filled in (one PATCH, no second click). Before this
 * existed, the Schedule button just flipped status with no date — drafts
 * went to "scheduled" but never showed up on the calendar.
 */
function ScheduleControl({
  draft,
  saving,
  onSchedule,
}: {
  draft: Draft;
  saving: boolean;
  onSchedule: (iso: string) => void;
}) {
  const [when, setWhen] = useState<string>(() =>
    draft.scheduled_for ? toLocalInput(draft.scheduled_for) : ""
  );
  // Re-sync local input value if the parent's scheduled_for changes underneath
  // (e.g. external patch arrived while the component instance was reused).
  // Without this, useState's initializer only runs once per mount, so the
  // displayed date could go stale.
  useEffect(() => {
    setWhen(draft.scheduled_for ? toLocalInput(draft.scheduled_for) : "");
  }, [draft.scheduled_for]);
  return (
    <div style={{ display: "inline-flex", gap: "0.4rem", alignItems: "center", flexWrap: "wrap" }}>
      <input
        type="datetime-local"
        value={when}
        onChange={(e) => setWhen(e.target.value)}
        aria-label="Schedule date and time"
        style={{
          ...selectStyle,
          padding: "0.4rem 0.7rem",
          fontSize: "0.78rem",
        }}
      />
      <button
        type="button"
        onClick={() => {
          if (!when) return;
          onSchedule(new Date(when).toISOString());
        }}
        style={primaryBtn}
        disabled={saving || !when}
      >
        Schedule
      </button>
    </div>
  );
}

/**
 * RescheduleControl — same shape, but for drafts already in "scheduled"
 * status. Lets the customer move a scheduled draft to a new date without
 * having to send it back to "draft" first.
 */
function RescheduleControl({
  draft,
  saving,
  onReschedule,
}: {
  draft: Draft;
  saving: boolean;
  onReschedule: (iso: string) => void;
}) {
  const [when, setWhen] = useState<string>(() =>
    draft.scheduled_for ? toLocalInput(draft.scheduled_for) : ""
  );
  // Sync the local input with the prop when the parent's scheduled_for changes
  // — same reasoning as ScheduleControl above. After a successful reschedule,
  // the new prop value flows in and "changed" goes back to falsy on its own.
  useEffect(() => {
    setWhen(draft.scheduled_for ? toLocalInput(draft.scheduled_for) : "");
  }, [draft.scheduled_for]);
  const changed = when && draft.scheduled_for && when !== toLocalInput(draft.scheduled_for);
  return (
    <div style={{ display: "inline-flex", gap: "0.4rem", alignItems: "center", flexWrap: "wrap" }}>
      <input
        type="datetime-local"
        value={when}
        onChange={(e) => setWhen(e.target.value)}
        aria-label="Reschedule date and time"
        style={{
          ...selectStyle,
          padding: "0.4rem 0.7rem",
          fontSize: "0.78rem",
        }}
      />
      {changed && (
        <button
          type="button"
          onClick={() => {
            if (!when) return;
            onReschedule(new Date(when).toISOString());
          }}
          style={primaryBtn}
          disabled={saving || !when}
        >
          Reschedule
        </button>
      )}
    </div>
  );
}
